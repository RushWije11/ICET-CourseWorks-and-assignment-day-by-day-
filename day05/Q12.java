class Q12{
	public static void main(String args[]){
		
		
		System.out.println("Print Hello World Using for-loop");
		for (int i = 1; i<=10; i++){
			System.out.println("     Hello world");
		}
		System.out.println();
			
		System.out.println("Print Hello World Using while-loop");
		
		int num = 0;
		while(num<10){
			System.out.println("     Hello world");
			num++;
		}
		
	}
}
